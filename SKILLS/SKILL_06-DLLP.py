image_lookup = {img["id"]: img for img in images}
category_ids = set(category_names.keys())

invalid_boxes = []
invalid_category = []
invalid_image_ids = []
out_of_bounds = []
invalid_dimensions = []

for ann in annotations:

    if ann["image_id"] not in image_lookup:
        invalid_image_ids.append(ann["id"])
        continue

    if ann["category_id"] not in category_ids:
        invalid_category.append(ann["id"])
        continue

    bbox = ann.get("bbox", [])

    if len(bbox) != 4:
        invalid_boxes.append(ann["id"])
        continue

    x, y, w, h = bbox

    if not all(np.isfinite(v) for v in bbox):
        invalid_boxes.append(ann["id"])
        continue

    if w <= 0 or h <= 0:
        invalid_dimensions.append(ann["id"])
        continue

    img_info = image_lookup[ann["image_id"]]

    if (
        x < 0 or y < 0 or
        x + w > img_info["width"] or
        y + h > img_info["height"]
    ):
        out_of_bounds.append(ann["id"])

print("Invalid bbox format:", len(invalid_boxes))
print("Invalid category IDs:", len(invalid_category))
print("Invalid image IDs:", len(invalid_image_ids))
print("Invalid box dimensions:", len(invalid_dimensions))
print("Boxes outside image:", len(out_of_bounds))

annotated_image_ids = set(
    ann["image_id"] for ann in annotations
)

unannotated_images = [
    img for img in images
    if img["id"] not in annotated_image_ids
]

print("Images without annotations:", len(unannotated_images))

random.seed(42)

samples = random.sample(
    images, min(5, len(images))
)

for info in samples:

    path = os.path.join(
        image_folder, info["file_name"]
    )

    if not os.path.exists(path):
        matches = glob(
            extract_path + "/**/" + os.path.basename(info["file_name"]),
            recursive=True
        )
        if matches:
            path = matches[0]

    img = cv2.imread(path)

    if img is None:
        continue

    img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)

    for ann in annotations:

        if ann["image_id"] != info["id"]:
            continue

        x, y, w, h = ann["bbox"]

        x1, y1 = int(x), int(y)
        x2, y2 = int(x+w), int(y+h)

        cv2.rectangle(
            img, (x1, y1), (x2, y2),
            (0, 255, 0), 2
        )

        label = category_names[ann["category_id"]]

        cv2.putText(
            img, label, (x1, max(20, y1-5)),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.5, (255, 0, 0), 2
        )

    plt.figure(figsize=(10, 7))
    plt.imshow(img)
    plt.title("Annotation Validation")
    plt.axis("off")
    plt.show()

