image_folder = os.path.dirname(annotation_file)

quality_data = []
corrupted_images = []

for info in images:
    path = os.path.join(image_folder, info["file_name"])

    if not os.path.exists(path):
        matches = glob(
            extract_path + "/**/" + os.path.basename(info["file_name"]),
            recursive=True
        )
        if matches:
            path = matches[0]

    img = cv2.imread(path)

    if img is None:
        corrupted_images.append(info["file_name"])
        continue

    gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)

    blur_score = cv2.Laplacian(
        gray, cv2.CV_64F
    ).var()

    brightness = gray.mean()

    height, width = img.shape[:2]

    quality_data.append({
        "Image": info["file_name"],
        "Width": width,
        "Height": height,
        "Blur Score": blur_score,
        "Brightness": brightness
    })

quality_df = pd.DataFrame(quality_data)

blur_threshold = 100

blurry_df = quality_df[
    quality_df["Blur Score"] < blur_threshold
]

