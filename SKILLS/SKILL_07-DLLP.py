import os
import torch
import onnx
import yaml
import shutil

from ultralytics import YOLO

print("All libraries imported successfully!")

# Load YOLOv8 Nano pretrained model
model = YOLO("yolov8n.pt")

# Display model architecture
model.info()

print("Model architecture loaded!")

os.makedirs("/content/skill7_outputs", exist_ok=True)

# Save architecture configuration
with open("/content/skill7_outputs/model_architecture.yaml", "w") as f:
    yaml.safe_dump(model.model.yaml, f)

print("Architecture configuration saved!")

# Save PyTorch checkpoint
model.save("/content/skill7_outputs/best.pt")

print("Checkpoint saved successfully!")

# Export model to ONNX
onnx_path = model.export(
    format="onnx",
    imgsz=640,
    opset=12,
    simplify=True
)

print("ONNX exported:", onnx_path)

# Load ONNX model
onnx_model = onnx.load(onnx_path)

# Check graph validity
onnx.checker.check_model(onnx_model)

print("ONNX model is valid!")
print("Graph inputs:", len(onnx_model.graph.input))
print("Graph outputs:", len(onnx_model.graph.output))

# Export TensorRT engine using FP16 precision
engine_path = model.export(
    format="engine",
    imgsz=640,
    half=True,
    device=0
)

print("TensorRT engine:", engine_path)

# Load TensorRT engine
trt_model = YOLO(engine_path)

# Test on a sample image
results = trt_model.predict(
    source="https://ultralytics.com/images/bus.jpg",
    conf=0.25,
    save=True
)

print("TensorRT inference completed!")

